#!/usr/bin/env python3
# Check that every "set <name>" in indiflight profiles is a CLI setting of the
# firmware: parses src/main/cli/settings.c (valueTable) plus the
# fc/parameter_names*.h macros, evaluating #if/#ifdef blocks for a set of
# build flags (default: the full indiflight flag set below plus each
# profile's own "#define" lines). Conditions it cannot evaluate count as true.
#
# usage: check_profile_settings.py [-D FLAG ...] configs/profiles/*.txt
#
# This file is part of Indiflight (GPL v3 or later).

import argparse, glob, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
FULL_FLAGS = ["USE_INDI", "USE_EKF", "USE_LOCAL_POSITION", "USE_POS_CTL", "USE_VEL_CTL",
              "USE_TELEMETRY_PI", "USE_GPS", "USE_GEOFENCE", "USE_BARO", "USE_PITOT", "USE_DSHOT",
              "USE_SERVOS", "USE_ACTUATORS_T4", "USE_BLACKBOX", "USE_ACC", "USE_GYRO", "USE_MAG",
              "USE_FRD_NED", "USE_DSHOT_TELEMETRY", "USE_OSD", "USE_LED_STRIP", "USE_SERIALRX",
              "USE_TELEMETRY", "USE_RPM_FILTER", "USE_DYN_NOTCH_FILTER", "USE_DYN_LPF",
              "USE_FEEDFORWARD", "USE_ITERM_RELAX", "USE_D_MAX", "USE_INTEGRATED_YAW_CONTROL",
              "USE_ABSOLUTE_CONTROL", "USE_LAUNCH_CONTROL", "USE_THRUST_LINEARIZATION",
              "USE_TPA_MODE", "USE_PINIO", "USE_PINIOBOX", "USE_BEEPER", "USE_ADC", "USE_VTX_COMMON"]
# INDI builds compile these out (target/common_post.h)
NOT_WITH_INDI = ["USE_GPS_RESCUE"]


def macros(paths):
    m = {}
    for p in paths:
        for name, val in re.findall(r'#define\s+(PARAM_NAME_\w+)\s+"([^"]+)"', open(p).read()):
            m[name] = val
    return m


def evalCond(cond, defined):
    expr = re.sub(r'//.*|/\*.*?\*/', '', cond).strip()
    expr = re.sub(r'defined\s*\(\s*(\w+)\s*\)', lambda mo: str(mo.group(1) in defined), expr)
    expr = re.sub(r'defined\s+(\w+)', lambda mo: str(mo.group(1) in defined), expr)
    expr = expr.replace('&&', ' and ').replace('||', ' or ').replace('!', ' not ')
    expr = expr.replace(' not =', '!=')
    try:
        return bool(eval(expr, {"__builtins__": {}}, {"True": True, "False": False}))
    except Exception:
        return True  # unknown macro / expression: assume the setting exists


def settingNames(defined):
    pdir = os.path.join(ROOT, "src", "main", "fc")
    names = macros(glob.glob(os.path.join(pdir, "parameter_names*.h")))
    src = open(os.path.join(ROOT, "src", "main", "cli", "settings.c")).read()
    start = src.index("const clivalue_t valueTable[]")
    found, stack = set(), []
    for line in src[start:].splitlines():
        s = line.strip()
        if s.startswith("#ifdef"):
            stack.append(s.split()[1] in defined)
        elif s.startswith("#ifndef"):
            stack.append(s.split()[1] not in defined)
        elif s.startswith("#if"):
            stack.append(evalCond(s[3:], defined))
        elif s.startswith("#elif"):
            stack[-1] = (not stack[-1]) and evalCond(s[5:], defined)
        elif s.startswith("#else"):
            stack[-1] = not stack[-1]
        elif s.startswith("#endif"):
            if not stack:
                break  # end of the table's enclosing block
            stack.pop()
        elif all(stack):
            gen = re.match(r'\{\s*"([a-z0-9_]+)"\s+STR\(N\)\s+"([a-z0-9_]+)"', s)
            if gen:  # per-device rows generated by a macro (gyro_1_..., gyro_2_...)
                found |= {f"{gen.group(1)}{n}{gen.group(2)}" for n in (1, 2)}
            mo = re.match(r'\{\s*(?:"([a-z0-9_]+)"|(PARAM_NAME_\w+))\s*,', s)
            if mo:
                found.add(mo.group(1) or names.get(mo.group(2), mo.group(2)))
        if s.startswith("};") and not stack and found:
            break
    return found


def targetDefines(config):
    # every USE_* the common target headers and the board config define
    files = [os.path.join(ROOT, "src", "main", "target", "common_pre.h")]
    files += glob.glob(os.path.join(ROOT, "src", "config", "configs", "*", config, "config.h"))
    flags = set()
    for f in files:
        flags |= set(re.findall(r'^\s*#define\s+(USE_\w+)', open(f).read(), re.M))
    return flags


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-D", action="append", default=[], help="extra build flag")
    ap.add_argument("--config", default="MATEKH743", help="upstream board config for the target defines")
    ap.add_argument("profiles", nargs="+")
    args = ap.parse_args()
    bad = 0
    for prof in args.profiles:
        text = open(prof).read()
        defined = set(FULL_FLAGS + args.D + re.findall(r'^#define\s+(\w+)', text, re.M)) | targetDefines(args.config)
        if "USE_INDI" in defined:
            defined -= set(NOT_WITH_INDI)
        valid = settingNames(defined)
        unknown = sorted({mo for mo in re.findall(r'^\s*set\s+([a-z0-9_]+)', text, re.M) if mo not in valid})
        print(f"{os.path.basename(prof)}: {len(unknown)} unknown" + (": " + ", ".join(unknown) if unknown else ""))
        bad += len(unknown)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
